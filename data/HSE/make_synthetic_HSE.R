code_draw <- function(n, p, missing = 0) {
  v <- as.numeric(sample(names(p), n, replace = TRUE, prob = as.numeric(p)))
  if (missing > 0) v[runif(n) < missing] <- NA_real_
  v
}

numeric_draw <- function(n, mean, sd, lo, hi, missing = 0) {
  v <- pmin(pmax(rnorm(n, mean, sd), lo), hi)
  if (missing > 0) v[runif(n) < missing] <- NA_real_
  v
}

write_wave <- function(d, path) {
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  haven::write_sav(d, path)
  message("wrote ", path, "  (", nrow(d), " rows, ", ncol(d), " columns)")
}

